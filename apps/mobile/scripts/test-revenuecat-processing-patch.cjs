/* Usage: node scripts/test-revenuecat-processing-patch.cjs <locked-RevenueCat-source-root> */
const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),assert=require('node:assert/strict');
const {patchPods,sourceFiles}=require('./patch-revenuecat-processing.cjs');
const {patchPodfile,oldBlock,block}=require('../plugins/withRevenueCatProcessing.cjs');
const sourceRoot=process.argv[2];
if(!sourceRoot) throw Error('Provide the cached official RevenueCat 5.88.0 source root');
const pods=fs.mkdtempSync(path.join(os.tmpdir(),'flapfit-rc-pods-'));
for(const name of sourceFiles){const target=path.join(pods,'RevenueCat',name);fs.mkdirSync(path.dirname(target),{recursive:true});fs.copyFileSync(path.join(sourceRoot,name),target);}
assert.equal(fs.existsSync(path.join(pods,'Local Podspecs')),false);
const versions={RevenueCat:'5.88.0',PurchasesHybridCommon:'18.37.0'};
for(const invalid of [undefined,null,{},[],{...versions,RevenueCat:'5.88.1'},{...versions,PurchasesHybridCommon:'18.37.1'}]) assert.throws(()=>patchPods(pods,invalid),/requires resolved/);
assert.equal(sourceFiles.length,10);
assert.equal(patchPods(pods,versions),sourceFiles.length);
assert.equal(patchPods(pods,versions),0);

const read=name=>fs.readFileSync(path.join(pods,'RevenueCat',name),'utf8');
const http=read('Sources/Networking/HTTPClient/HTTPClient.swift');
const endpointGate=http.indexOf('guard request.path is HTTPRequest.AdPath else');
assert.ok(endpointGate>0 && endpointGate<http.indexOf('self.perform(request: .init(httpRequest: request,'));
assert.ok(!http.includes('headers["X-Apple-Device-Identifier"]'));
assert.match(http,/static let allowsNonAdProcessing = false/);
assert.match(http,/guard FFRevenueCatProcessingGate.allowsNonAdProcessing else \{ completion\(\.failure\(URLError\(\.cancelled\)\)\); return \}/);
assert.match(read('Sources/Networking/RemoteConfigBlobDownloader.swift'),/guard FFRevenueCatProcessingGate.allowsNonAdProcessing else \{ throw URLError\(\.cancelled\) \}/);
const purchases=read('Sources/Purchasing/Purchases/Purchases.swift');
assert.ok(!purchases.includes('self.performInitialForegroundSetup()'));
assert.ok(!purchases.includes('self.attributionPoster.postPostponedAttributionDataIfNeeded()'));
assert.ok(!purchases.includes('self.transactionMetadataSyncHelper.syncIfNeeded('));
assert.ok(!purchases.includes('self.paymentQueueWrapper.sk1Wrapper?.delegate = purchasesOrchestrator'));
assert.ok(!purchases.includes('self.paymentQueueWrapper.sk2Wrapper?.delegate = purchasesOrchestrator'));
assert.ok(!purchases.includes('purchasesOrchestrator.setSK2PurchaseIntentListener(StoreKit2PurchaseIntentListener())'));
assert.ok(purchases.includes('automaticDeviceIdentifierCollectionEnabled: false) // Flap Fit'));
const foreground=purchases.slice(purchases.indexOf('    @objc func applicationWillEnterForeground()'),purchases.indexOf('    @objc func applicationDidEnterBackground()'));
assert.ok(foreground.includes('postEventsIfNeeded(delayed: true)'));
for(const denied of ['updateAllCaches','syncSubscriberAttributes','postAdServicesToken','transactionMetadataSyncHelper','logInIfNeeded'])assert.ok(!foreground.includes(denied));
assert.ok(purchases.includes('self.purchasesOrchestrator.postEventsIfNeeded()'));
const orchestrator=read('Sources/Purchasing/Purchases/PurchasesOrchestrator.swift');
const constructor=orchestrator.slice(orchestrator.indexOf('self._diagnosticsSynchronizer = diagnosticsSynchronizer'),orchestrator.indexOf('    init(productsManager: ProductsManagerType,'));
for(const denied of ['listenForStorefrontChanges()','deferMessagesIfNeeded()','await setSK2DelegateAndStartListening()','await syncDiagnosticsIfNeeded()'])assert.ok(!constructor.includes(denied));
assert.match(read('Sources/Misc/SystemInfo.swift'),/var remoteConfigEnabled: Bool \{\s*return false/);
assert.match(read('Sources/Events/EventsManager.swift'),/func track\(featureEvent: FeatureEvent\) async \{\s*guard FFRevenueCatProcessingGate.allowsNonAdProcessing else \{ return \}/);
// The genuine ad store, SDK serialization, operation and HTTP request remain.
assert.ok(read('Sources/Events/EventsManager.swift').includes('self.internalAPI.postAdEvents(events: events)'));
assert.ok(read('Sources/Ads/Events/Networking/PostAdEventsOperation.swift').includes('self.httpClient.perform(httpRequest)'));
const {spawnSync}=require('node:child_process');
const cli=spawnSync(process.execPath,[path.join(__dirname,'patch-revenuecat-processing.cjs'),pods,JSON.stringify(versions)],{encoding:'utf8'});
assert.equal(cli.status,0,cli.stderr);
assert.match(cli.stdout,/0 files patched/);
const missing=spawnSync(process.execPath,[path.join(__dirname,'patch-revenuecat-processing.cjs'),pods],{encoding:'utf8'});
assert.notEqual(missing.status,0);
assert.match(missing.stderr,/requires resolved/);
const target=path.join(pods,'RevenueCat',sourceFiles[0]),good=fs.readFileSync(target,'utf8');
fs.writeFileSync(target,good+'// tamper');
assert.throws(()=>patchPods(pods,versions),/Modified RevenueCat consent fence/);
fs.writeFileSync(target,good);
const input="target 'FlapFit' do\n  post_install do |installer|\n    react_native_post_install(installer)\n  end\nend\n";
const result=patchPodfile(input);
assert.equal(patchPodfile(result),result);
const old=input.replace('post_install do |installer|','post_install do |installer|\n    '+oldBlock);
assert.equal(patchPodfile(old),result);
assert.ok(result.includes('installer.pod_targets.each'));
assert.ok(result.includes('spec = target.root_spec'));
assert.ok(result.includes('spec.version.to_s'));
assert.ok(result.includes('JSON.generate(ff_rc_versions)'));
assert.throws(()=>patchPodfile(result.replace('JSON.generate(ff_rc_versions)',"'wrong'")),/modified Podfile integration/);
assert.ok(!block.includes('Local Podspecs'));
console.log('RC patch checks passed: no Local Podspecs directory, exact resolved versions, missing/mismatched versions rejected, ten pinned patches; ad-only endpoint routing, no IDFV/purchase/config startup, genuine ad delivery preserved, idempotence, tamper rejection, Podfile migration and safe JSON argument.');
